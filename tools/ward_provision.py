#!/usr/bin/env python3
"""Provision the production WM public key from an explicitly selected manager seed."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

ROOT = Path(__file__).resolve().parent.parent


def render(public_key: str | None) -> str:
    if public_key is not None:
        key = bytes.fromhex(public_key)
        if len(key) != 32 or key == bytes(32):
            raise ValueError("a nonzero 32-byte public key is required")
    else:
        key = bytes(32)
    return (
        "# Generated by tools/ward_provision.py. Do not edit.\n"
        f'WM_PUBLIC_KEY = bytes.fromhex("{key.hex()}")\n'
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--config", type=Path, default=ROOT / "common/ward-manager.json"
    )
    parser.add_argument(
        "--output", type=Path, default=ROOT / "core/src/apps/ward/wm_config.py"
    )
    parser.add_argument(
        "--key-file",
        "--seed-file",
        dest="seed_file",
        type=Path,
        help="The same hex signing-seed file used by ward_manager.py --key-file",
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check and args.seed_file:
        parser.error("--check does not modify a provisioned key")
    if args.seed_file:
        seed = bytes.fromhex(args.seed_file.read_text().strip())
        if len(seed) != 32:
            parser.error("manager seed must be decode to exactly 32 bytes")
        public_key = (
            Ed25519PrivateKey.from_private_bytes(seed)
            .public_key()
            .public_bytes_raw()
            .hex()
        )
        args.config.write_text(json.dumps({"public_key": public_key}, indent=2) + "\n")
    public_key = json.loads(args.config.read_text())["public_key"]
    source = render(public_key)
    if args.check:
        return 0 if args.output.is_file() and args.output.read_text() == source else 1
    args.output.write_text(source)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
