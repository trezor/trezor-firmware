#!/usr/bin/env python3

from __future__ import annotations

import typing as t
from pathlib import Path

import click
import yaml

ROOT = Path(__file__).resolve().parent.parent.parent
OPTIGA_CERTS_DIR = ROOT / "core/embed/sec/optiga/unix/certs"
MCU_CERTS_DIR = ROOT / "core/embed/sec/secret/unix/certs"
TROPIC_BASE_CONFIG = ROOT / "tests/tropic_model/base_config.yml"
TROPIC_MODEL = "T3W1"
# Tropic user data slots holding the device certificate chain
TROPIC_CERT_CHAIN_SLOTS = (3, 4, 5)
PYTHON_TEST_CERTS_DIR = ROOT / "python/tests/emulator_certs"

SCRIPT = Path(__file__).relative_to(ROOT)
COMMENT = f"""// This file is auto-generated by `{SCRIPT}`.
// Do not edit this file directly. Instead, run `make gen` or `make certs`
// in the root directory."""


class EmulatorCert(t.NamedTuple):
    attestation_source: str
    model: str
    data: bytes
    header_path: Path | None = None
    variable_name: str | None = None


def bytes_to_header(data: bytes, variable_name: str) -> str:
    chunks = [data[i : i + 12] for i in range(0, len(data), 12)]
    byte_lines = [", ".join(f"0x{b:02x}" for b in chunk) for chunk in chunks]

    define_lines = [f"#define {variable_name}", "  {"]
    for byte_line in byte_lines:
        define_lines.append(f"      {byte_line},")
    define_lines.append("  }")

    width = max(len(line) for line in define_lines[:-1]) + 1
    for i in range(len(define_lines) - 1):
        define_lines[i] = define_lines[i].ljust(width) + "\\"

    lines = [COMMENT, "", *define_lines]
    return "\n".join(lines) + "\n"


def missing_source(path: Path) -> click.ClickException:
    return click.ClickException(
        f"{path} is missing. If it was moved or renamed, update the path in {SCRIPT}."
    )


def find_der_certs(
    certs_dir: Path, attestation_source: str, variable_name: str
) -> list[EmulatorCert]:
    """Find the <MODEL>.der certificates in `certs_dir`."""
    der_paths = sorted(certs_dir.glob("*.der"))
    if not der_paths:
        raise missing_source(certs_dir)
    return [
        EmulatorCert(
            attestation_source=attestation_source,
            model=der_path.stem,
            data=der_path.read_bytes(),
            header_path=der_path.with_suffix(".h"),
            variable_name=variable_name,
        )
        for der_path in der_paths
    ]


def find_tropic_cert() -> EmulatorCert:
    if not TROPIC_BASE_CONFIG.exists():
        raise missing_source(TROPIC_BASE_CONFIG)
    config = yaml.safe_load(TROPIC_BASE_CONFIG.read_bytes())
    data = b"".join(
        config["r_user_data"][slot]["value"] for slot in TROPIC_CERT_CHAIN_SLOTS
    )
    length = int.from_bytes(data[:2], "big")
    return EmulatorCert(
        attestation_source="tropic", model=TROPIC_MODEL, data=data[2 : 2 + length]
    )


def find_emulator_certs() -> list[EmulatorCert]:
    return [
        *find_der_certs(OPTIGA_CERTS_DIR, "optiga", "OPTIGA_DEVICE_CERT_CHAIN"),
        *find_der_certs(MCU_CERTS_DIR, "mcu", "MCU_DEVICE_CERT"),
        find_tropic_cert(),
    ]


def write_or_check(path: Path, content: bytes, check: bool) -> None:
    if check:
        if not path.exists():
            raise click.ClickException(f"{path} is missing")
        if path.read_bytes() != content:
            raise click.ClickException(f"{path} is out of date")
    else:
        path.write_bytes(content)
        print(f"Generated {path}")


def generate_headers(certs: list[EmulatorCert], check: bool) -> None:
    """Generate the C headers compiled into the emulator."""
    for cert in certs:
        if cert.header_path is None or cert.variable_name is None:
            continue
        header = bytes_to_header(cert.data, cert.variable_name)
        write_or_check(cert.header_path, header.encode(), check)


def generate_test_certs(certs: list[EmulatorCert], check: bool) -> None:
    """Copy the certificates for trezorlib tests and remove stale copies."""
    test_cert_paths = set()
    for cert in certs:
        path = PYTHON_TEST_CERTS_DIR / f"{cert.attestation_source}_{cert.model}.der"
        write_or_check(path, cert.data, check)
        test_cert_paths.add(path)

    for path in sorted(set(PYTHON_TEST_CERTS_DIR.glob("*.der")) - test_cert_paths):
        if check:
            raise click.ClickException(
                f"{path} does not match any emulator certificate. Run `make certs`."
            )
        path.unlink()
        print(f"Removed {path}")


@click.command()
@click.option("--check", is_flag=True)
def generate(check: bool) -> None:
    certs = find_emulator_certs()
    generate_headers(certs, check)
    generate_test_certs(certs, check)

    if check:
        print("All files are up to date.")


if __name__ == "__main__":
    generate()
