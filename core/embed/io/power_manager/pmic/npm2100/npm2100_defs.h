// ADC conversion results (8-bit, see datasheet 7.1)
//   VBAT [V]  = RESULT * 3.2 / 255
//   VOUT [V]  = 1.8 + RESULT * 1.5 / 255
//   DIETEMP [C] = 389.5 - 2.12 * RESULT
