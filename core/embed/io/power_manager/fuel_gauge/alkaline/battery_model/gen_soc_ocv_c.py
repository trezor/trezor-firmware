#!/usr/bin/env python3
"""
gen_soc_ocv_c.py - compact C data for soc_ocv_lut.c / soc_ocv_poly.c from the fitted models.

    python c/tools/gen_soc_ocv_c.py [models/lut_model.json] [models/poly_model.json]   (from ocv_soc/)

Encodings (all const, placed in flash):
  temperature spans   int8,   0.5 degC        (exact: the tuned spans are multiples of 0.5 degC)
  voltage ranges      uint16, mV              (exact: OCV data has 1 mV resolution)
  table SoC values    uint8,  0.5 % (0..200)  (rounding <= 0.25 % SoC; stays monotone)
  poly coefficients   int16,  0.01 %          (rounding <= 0.005 % each)
Writes c/include/soc_ocv_data.h, c/src/soc_ocv_data.c and c/test/test_vectors.h (Python reference
values on a grid and on every lab OCV point, for test_soc_ocv.c).
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, ROOT)
from ocv_common import load_ocv_points  # noqa: E402
from soc_ocv_lut import OcvLut  # noqa: E402
from soc_ocv_poly import OcvPoly  # noqa: E402

C = os.path.join(ROOT, "c")


def exact(x, scale, what):
    v = round(x * scale)
    if abs(v - x * scale) > 1e-6:
        raise SystemExit(f"{what} = {x} is not a multiple of 1/{scale}")
    return v


def main():
    lut_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "models", "lut_model.json")
    poly_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "models", "poly_model.json")
    lut, poly = OcvLut.load(lut_path), OcvPoly.load(poly_path)
    ln, pn = list(lut.nodes.values()), list(poly.nodes.values())
    npts, ncoef = len(ln[0]["soc"]), len(pn[0]["coef"])
    assert all(len(n["soc"]) == npts for n in ln) and all(len(n["coef"]) == ncoef for n in pn)

    lut_span = [(exact(n["t_lo"], 2, "span"), exact(n["t_hi"], 2, "span")) for n in ln]
    lut_vr = [(exact(n["v0"], 1000, "v0"), exact(n["v0"] + n["step"] * (npts - 1), 1000, "v_end")) for n in ln]
    lut_q = [[int(round(s * 2)) for s in n["soc"]] for n in ln]
    poly_span = [(exact(n["t_lo"], 2, "span"), exact(n["t_hi"], 2, "span")) for n in pn]
    poly_vr = [(exact(n["vmin"], 1000, "vmin"), exact(n["vmax"], 1000, "vmax")) for n in pn]
    poly_c = [[int(round(c * 100)) for c in n["coef"]] for n in pn]
    for spans in (lut_span, poly_span):
        assert all(-128 <= a <= b <= 127 for a, b in spans)
    assert all(0 < a < b < 65536 for a, b in lut_vr + poly_vr)
    assert all(0 <= q <= 200 for row in lut_q for q in row) and all(b >= a for row in lut_q for a, b in zip(row, row[1:]))
    assert all(-32768 <= c <= 32767 for row in poly_c for c in row)
    # Horner in int32: |acc| <= sum|c| (|x| <= 1), and acc * x_q15 must fit in int32
    assert all(sum(abs(c) for c in row) * 32768 < 2 ** 31 for row in poly_c), "coefficients too large for int32 Horner"

    rows = lambda vals, fmt: ", ".join(fmt.format(v) for v in vals)
    h = ["/* Generated by c/tools/gen_soc_ocv_c.py from the fitted models - do not edit. */",
         "#ifndef SOC_OCV_DATA_H", "#define SOC_OCV_DATA_H", "", "#include <stdint.h>", "",
         f"#define SOC_OCV_LUT_TEMPS   ({len(ln)}U)", f"#define SOC_OCV_LUT_POINTS  ({npts}U)",
         f"#define SOC_OCV_POLY_TEMPS  ({len(pn)}U)", f"#define SOC_OCV_POLY_COEFS  ({ncoef}U)", "",
         "/* [k][0..1]: temperature span (first, last) in which curve k applies fully, 0.5 degC units */",
         "extern const int8_t soc_ocv_lut_span[SOC_OCV_LUT_TEMPS][2];",
         "/* [k][0..1]: OCV of the first and the last table point in mV; points evenly spaced between */",
         "extern const uint16_t soc_ocv_lut_vrange[SOC_OCV_LUT_TEMPS][2];",
         "/* [k][i]: SoC at table point i in 0.5 % units (0..200), non-decreasing in i */",
         "extern const uint8_t soc_ocv_lut_soc[SOC_OCV_LUT_TEMPS][SOC_OCV_LUT_POINTS];", "",
         "extern const int8_t soc_ocv_poly_span[SOC_OCV_POLY_TEMPS][2];",
         "/* [k][0..1]: OCV range of polynomial k in mV (input clamped to it) */",
         "extern const uint16_t soc_ocv_poly_vrange[SOC_OCV_POLY_TEMPS][2];",
         "/* [k][c]: coefficient of x^c in 0.01 % units, x = (2 OCV - (min + max)) / (max - min) */",
         "extern const int16_t soc_ocv_poly_coef[SOC_OCV_POLY_TEMPS][SOC_OCV_POLY_COEFS];", "",
         "#endif /* SOC_OCV_DATA_H */", ""]
    c = ["/* Generated by c/tools/gen_soc_ocv_c.py from the fitted models - do not edit.",
         f" * calibration set points: {', '.join(f'{t:g} degC' for t in lut.nodes)} */",
         '#include "soc_ocv_data.h"', "",
         "const int8_t soc_ocv_lut_span[SOC_OCV_LUT_TEMPS][2] = {" + rows(lut_span, "{{{0[0]}, {0[1]}}}") + "};",
         "const uint16_t soc_ocv_lut_vrange[SOC_OCV_LUT_TEMPS][2] = {" + rows(lut_vr, "{{{0[0]}U, {0[1]}U}}") + "};",
         "const uint8_t soc_ocv_lut_soc[SOC_OCV_LUT_TEMPS][SOC_OCV_LUT_POINTS] = {"]
    c += ["    {" + rows(r, "{}U") + "}," for r in lut_q] + ["};", "",
          "const int8_t soc_ocv_poly_span[SOC_OCV_POLY_TEMPS][2] = {" + rows(poly_span, "{{{0[0]}, {0[1]}}}") + "};",
          "const uint16_t soc_ocv_poly_vrange[SOC_OCV_POLY_TEMPS][2] = {" + rows(poly_vr, "{{{0[0]}U, {0[1]}U}}") + "};",
          "const int16_t soc_ocv_poly_coef[SOC_OCV_POLY_TEMPS][SOC_OCV_POLY_COEFS] = {"]
    c += ["    {" + rows(r, "{}") + "}," for r in poly_c] + ["};", ""]
    open(os.path.join(C, "include", "soc_ocv_data.h"), "w").write("\n".join(h))
    open(os.path.join(C, "src", "soc_ocv_data.c"), "w").write("\n".join(c))

    # ---- reference vectors from the (float) Python models
    mv = np.arange(1000, 1701, 5)
    dc = np.arange(-150, 551, 50)
    g_mv, g_dc = [a.ravel() for a in np.meshgrid(mv, dc)]
    g_lut, g_poly = lut.estimate(g_mv / 1000.0, g_dc / 10.0), poly.estimate(g_mv / 1000.0, g_dc / 10.0)
    with open(os.path.join(ROOT, "logs.txt")) as f:
        names = [x.strip() for x in f if x.strip()]
    logdir = os.environ.get("OCV_LOG_DIR", "/mnt/user-data/uploads")
    pts = load_ocv_points([os.path.join(logdir, n) for n in names])
    p_mv = np.round(pts.ocv.to_numpy() * 1000).astype(int)
    p_dc = np.round(pts.T_meas.to_numpy() * 10).astype(int)
    p_lut, p_poly = lut.estimate(p_mv / 1000.0, p_dc / 10.0), poly.estimate(p_mv / 1000.0, p_dc / 10.0)
    t = ["/* Generated by c/tools/gen_soc_ocv_c.py - Python (float) reference values. */",
         "#ifndef TEST_VECTORS_H", "#define TEST_VECTORS_H", "#include <stdint.h>",
         "typedef struct { uint16_t mv; int16_t dc; float lut; float poly; } tv_grid_t;",
         "typedef struct { uint16_t mv; int16_t dc; float truth; float lut; float poly; } tv_point_t;",
         f"#define TV_NGRID ({len(g_mv)}U)", "static const tv_grid_t tv_grid[TV_NGRID] = {"]
    t += [f"    {{{a}U, {b}, {x:.5f}f, {y:.5f}f}}," for a, b, x, y in zip(g_mv, g_dc, g_lut, g_poly)]
    t += ["};", f"#define TV_NPOINTS ({len(p_mv)}U)", "static const tv_point_t tv_points[TV_NPOINTS] = {"]
    t += [f"    {{{a}U, {b}, {s:.4f}f, {x:.5f}f, {y:.5f}f}}," for a, b, s, x, y in zip(p_mv, p_dc, pts.soc, p_lut, p_poly)]
    t += ["};", "#endif", ""]
    open(os.path.join(C, "test", "test_vectors.h"), "w").write("\n".join(t))
    print(f"data: {len(ln)} tables x {npts} points, {len(pn)} polynomials x {ncoef} coefficients; "
          f"vectors: {len(g_mv)} grid + {len(p_mv)} lab points")


if __name__ == "__main__":
    main()
