use std::path::{Path, PathBuf};

use color_eyre::Result;
use color_eyre::eyre::Context;

use super::CLibrary;
use crate::cargo_out;
use crate::helpers::path_from_env;

impl CLibrary {
    /// Generate C bindings for the specified header using cbindgen.
    /// Header files are generated in the `OUT_DIR/cbindgen` directory.
    /// Takes the relative path to the C header file and a closure to modify the
    /// cbindgen::Builder.
    pub fn add_c_bindings(
        &mut self,
        header: impl AsRef<Path>,
        func: impl FnOnce(cbindgen::Builder) -> Result<cbindgen::Builder>,
    ) -> Result<()> {
        let out_dir = path_from_env("OUT_DIR")?;
        let cbindgen_dir = out_dir.join("cbindgen");
        let header_path = cbindgen_dir.join(header);

        self.add_include(&cbindgen_dir);

        let mut config = cbindgen::Config::default();
        config.layout.packed = Some("__attribute__((packed))".into());

        let builder = cbindgen::Builder::new()
            .with_config(config)
            .with_language(cbindgen::Language::C)
            .with_style(cbindgen::Style::Type)
            .with_no_includes()
            .with_pragma_once(true)
            .with_header("/* Automatically generated by cbindgen, do not edit. */");

        let bindings = func(builder)?
            .generate()
            .context("Unable to generate bindings")?;

        bindings.write_to_file(&header_path);

        // Generate a depfile for the header to track dependencies
        // (cbindgen doesn't provide direct api to list dependencies)
        let depfile = header_path.with_added_extension("d");
        bindings.generate_depfile(&header_path, &depfile);

        // Parse depfile and add each dependency to cargo's rerun-if-changed list
        let deps = std::fs::read_to_string(&depfile).context("Unable to read depfile")?;
        for dep in parse_depfile(&deps) {
            cargo_out::rerun_if_changed(dep);
        }

        Ok(())
    }
}

/// Parses a Makefile-style depfile written by
/// `cbindgen::Bindings::generate_depfile` and returns the listed dependencies
/// (every path after the target line), sorted and deduplicated (cbindgen lists
/// the root source twice).
fn parse_depfile(contents: &str) -> Vec<PathBuf> {
    let mut deps: Vec<PathBuf> = contents
        .lines()
        .skip(1)
        .map(|line| {
            line.trim()
                .trim_end_matches('\\')
                .trim()
                .replace("\\ ", " ")
        })
        .filter(|dep| !dep.is_empty())
        .map(PathBuf::from)
        .collect();
    deps.sort();
    deps.dedup();
    deps
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Runs real cbindgen on a tiny crate with a submodule and checks that the
    /// depfile it writes is still in the format `parse_depfile` understands,
    /// that it lists transitively parsed files and that escaped spaces in
    /// paths are decoded.
    #[test]
    fn parses_depfile_generated_by_cbindgen() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = tmp.path().join("dir with spaces");
        std::fs::create_dir(&dir).unwrap();
        let api = dir.join("api.rs");
        let sub = dir.join("sub.rs");
        std::fs::write(
            &api,
            "pub mod sub;\n#[unsafe(no_mangle)]\npub extern \"C\" fn api_fn() {}\n",
        )
        .unwrap();
        std::fs::write(
            &sub,
            "#[unsafe(no_mangle)]\npub extern \"C\" fn sub_fn() {}\n",
        )
        .unwrap();

        let header = dir.join("api.h");
        let depfile = header.with_added_extension("d");
        let bindings = cbindgen::Builder::new()
            .with_language(cbindgen::Language::C)
            .with_src(&api)
            .generate()
            .unwrap();
        bindings.write_to_file(&header);
        bindings.generate_depfile(&header, &depfile);

        let deps = parse_depfile(&std::fs::read_to_string(&depfile).unwrap());
        let mut expected = vec![api.canonicalize().unwrap(), sub.canonicalize().unwrap()];
        expected.sort();
        assert_eq!(deps, expected);
    }
}
