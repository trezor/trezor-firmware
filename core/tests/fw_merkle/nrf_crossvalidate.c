/*
 * Host cross-validation for the nRF founder-tree device verify.
 *
 * Compiles the REAL on-device fold (nrf_image.c: nrf_image_verify_in_tree) and
 * MCUboot model-id parse (io/nrf_image.h) with a host SHA-256, and replays a
 * vector produced by the host signer (gen_nrf_vector.py -> nrf_tree.py). Proves
 * the COMBINED device check (fold to modelRoot AND model-id TLV == this device)
 * matches Python: the genuine image passes, a tampered image fails the fold, and
 * ANOTHER model's nRF -- which folds to modelRoot fine -- is rejected on its
 * model id.
 *
 * Build (from core/):
 *   gcc -I embed/sec/image/stm32 -I embed/io/nrf/inc -I ../crypto -I <vecdir> \
 *       tests/fw_merkle/nrf_crossvalidate.c ../crypto/sha2.c ../crypto/memzero.c -o /tmp/nrf_cross
 */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "sha2.h"

/* --- shims the shared header expects (same as crossvalidate.c) --------- */
#include "shims_nrf.h"


#include <io/nrf_image.h> /* nrf_image_model_id (the model-id TLV) */

#include "nrf_vector.h" /* generated by gen_nrf_vector.py */

/* The nRF's own founder verify (MCUboot fork: boot/bootutil/src/image_pq.c),
 * compiled here with PQ_HOST_TEST so it uses the same host SHA-256 as the STM
 * code above -- so this really compares implementations, not hash backends. */
#include "bootutil/image_pq.h"

/* trezor-crypto's consteq() calls this if its loop-completion check fails. The
 * bootloader supplies a real one (image_validate.c); this stands in for it here,
 * loud and terminating so a fault fails the run rather than hanging it. */
void tc_fault_handler(const char *msg) {
  printf("FAULT: %s\n", msg);
  abort();
}

/* Unpack a wire artifact (proof_count || co_path || image), then run the two
 * checks the device runs on a staged image: fold to modelRoot, then pin the model
 * id.
 *
 * The unpacking is HARNESS scaffolding, not a mirror of production: the bootloader
 * never sees this wrapper as one buffer -- it gets co_path and image_len from its
 * staging descriptor (nrf_staging_read) and calls the same two primitives below.
 * Keeping the unpacking here, clearly separated, is what lets these cases exercise
 * the primitives rather than a convenience wrapper nothing ships. (There used to be
 * an io/nrf_ota.h doing this inline; it had no production caller.) */
static secbool harness_ota_gate(const uint8_t *artifact, size_t artifact_len,
                                const merkle_proof_node_t *trusted_model_root,
                                const uint8_t device_model_id[4],
                                const uint8_t **out_image,
                                size_t *out_image_len) {
  if (out_image != NULL) {
    *out_image = NULL;
  }
  if (out_image_len != NULL) {
    *out_image_len = 0;
  }
  if (artifact_len < sizeof(uint32_t)) {
    return secfalse;
  }
  uint32_t proof_count;
  memcpy(&proof_count, artifact, sizeof(proof_count));
  if (proof_count > MODEL_TREE_MAX_PROOF_NODES) {
    return secfalse;
  }
  size_t header_bytes =
      sizeof(uint32_t) + (size_t)proof_count * sizeof(merkle_proof_node_t);
  if (header_bytes >= artifact_len) {
    return secfalse;
  }
  const merkle_proof_node_t *co_path =
      (const merkle_proof_node_t *)(artifact + sizeof(uint32_t));
  const uint8_t *image = artifact + header_bytes;
  size_t image_len = artifact_len - header_bytes;

  if (nrf_image_verify_in_tree(image, image_len, co_path, proof_count,
                         trusted_model_root) != sectrue) {
    return secfalse;
  }
  uint8_t model_id[4];
  if (!nrf_image_model_id(image, image_len, model_id)) {
    return secfalse;
  }
  if (memcmp(model_id, device_model_id, 4) != 0) {
    return secfalse;
  }
  if (out_image != NULL) {
    *out_image = image;
  }
  if (out_image_len != NULL) {
    *out_image_len = image_len;
  }
  return sectrue;
}

/* Reader shim: on device the image is read through a flash_area; here it is a flat
 * buffer. Bounds-checked, so an out-of-range read fails rather than reading past
 * the fixture (which would mask a too-wide leaf). */
struct flat_image {
  const uint8_t *buf;
  uint32_t len;
};

static int flat_read(void *ctx, uint32_t off, void *dst, uint32_t len) {
  const struct flat_image *img = (const struct flat_image *)ctx;
  if ((uint64_t)off + len > (uint64_t)img->len) {
    return -1;
  }
  memcpy(dst, img->buf + off, len);
  return 0;
}

int main(void) {
  merkle_proof_node_t root;
  memcpy(root.bytes, NRF_MODEL_ROOT, 32);
  int fails = 0;

  /* model-id parse sanity */
  uint8_t mid[4];
  if (nrf_image_model_id(NRF_IMAGE, NRF_IMAGE_LEN, mid) &&
      memcmp(mid, DEVICE_MODEL_ID, 4) == 0) {
    printf("model-id TLV parse: %.4s OK\n", mid);
  } else {
    printf("FAIL: model-id parse\n");
    fails++;
  }

  /* genuine OTA artifact: parses, folds to modelRoot, model id == this device;
   * out_image must point at the inner MCUboot image (what nrf_update pushes). */
  const uint8_t *img = NULL;
  size_t img_len = 0;
  if (harness_ota_gate(NRF_OTA, NRF_OTA_LEN, &root, DEVICE_MODEL_ID, &img,
                     &img_len) != sectrue) {
    printf("FAIL: genuine OTA artifact rejected\n");
    fails++;
  } else if (img_len != NRF_IMAGE_LEN ||
             memcmp(img, NRF_IMAGE, NRF_IMAGE_LEN) != 0) {
    printf("FAIL: OTA out_image != embedded NRF_IMAGE\n");
    fails++;
  } else {
    printf("genuine OTA verify (parse + fold + model id, out_image): OK\n");
  }

  /* CLASSIC image (no founder TLVs): tamper BELOW prot_end -- the range MCUboot's
   * image hash, hence the leaf, covers -- must break the fold. Above it (its own
   * signature TLVs) is a separate case below, and is NOT the fold's job. */
  static uint8_t bad_ota[sizeof(NRF_OTA)];
  memcpy(bad_ota, NRF_OTA, NRF_OTA_LEN);
  bad_ota[NRF_OTA_IMAGE_OFF + NRF_IMAGE_PROT_END / 2] ^= 0xFF;
  if (harness_ota_gate(bad_ota, NRF_OTA_LEN, &root, DEVICE_MODEL_ID, &img,
                     &img_len) != secfalse) {
    printf("FAIL: classic tampered (body) OTA accepted\n");
    fails++;
  } else if (img != NULL || img_len != 0) {
    printf("FAIL: reject did not clear out_image\n");
    fails++;
  } else {
    printf("classic: tamper in body rejected (fold): OK\n");
  }

  /* Tamper INSIDE the unprotected area (last byte == the classic image-signature
   * TLV). The fold does NOT catch this, and must not be expected to: the leaf is
   * the MCUboot image hash, which stops at the protected TLVs. Asserting the fold
   * still folds is the point -- it pins where the boundary is, so a future change
   * that silently widened or narrowed it would show up here.
   *
   * What actually rejects this image is the per-scheme acceptance check the STM
   * runs before pushing (Ed25519 verification against the nRF's own key pool for a
   * classic image), plus the structural whitelist. Neither is exercised here; both
   * belong to the push gate, which has its own cases below. */
  memcpy(bad_ota, NRF_OTA, NRF_OTA_LEN);
  bad_ota[NRF_OTA_LEN - 1] ^= 0xFF;
  if (harness_ota_gate(bad_ota, NRF_OTA_LEN, &root, DEVICE_MODEL_ID, NULL, NULL) !=
      sectrue) {
    printf("FAIL: classic unprotected tamper broke the fold "
           "(leaf boundary moved?)\n");
    fails++;
  } else {
    printf("classic: unprotected tamper still folds (leaf stops at prot): OK\n");
  }

  /* PQ-NATIVE image (founder TLVs): genuine artifact folds, using a leaf that
   * stops before the founder material. */
  if (harness_ota_gate(PQ_OTA, PQ_OTA_LEN, &root, DEVICE_MODEL_ID, NULL, NULL) !=
      sectrue) {
    printf("FAIL: genuine PQ-native OTA rejected\n");
    fails++;
  } else {
    printf("PQ-native: genuine OTA verify (leaf == image hash): OK\n");
  }

  /* PQ-native, tamper INSIDE the covered range -> must break the fold */
  static uint8_t bad_pq[sizeof(PQ_OTA)];
  memcpy(bad_pq, PQ_OTA, PQ_OTA_LEN);
  bad_pq[NRF_OTA_IMAGE_OFF + PQ_IMAGE_PROT_END / 2] ^= 0xFF;
  if (harness_ota_gate(bad_pq, PQ_OTA_LEN, &root, DEVICE_MODEL_ID, NULL, NULL) !=
      secfalse) {
    printf("FAIL: PQ-native tamper inside covered range accepted\n");
    fails++;
  } else {
    printf("PQ-native: tamper inside covered range rejected: OK\n");
  }

  /* PQ-native, tamper in the FOUNDER MATERIAL -> BY DESIGN still folds: that
   * material signs modelRoot, so it cannot be inside its own leaf. This is exactly
   * why the STM must ALSO verify the founder material before overwriting a working
   * nRF (no dual slot). Asserted so the boundary cannot drift silently. */
  memcpy(bad_pq, PQ_OTA, PQ_OTA_LEN);
  bad_pq[PQ_OTA_LEN - 1] ^= 0xFF;
  if (harness_ota_gate(bad_pq, PQ_OTA_LEN, &root, DEVICE_MODEL_ID, NULL, NULL) !=
      sectrue) {
    printf("FAIL: PQ-native founder-material tamper broke the fold\n");
    fails++;
  } else {
    printf("PQ-native: founder-material tamper still folds (by design): OK\n");
  }

  /* ---- THIRD implementation: the nRF's own (MCUboot image_pq.c) --------
   * The nRF verifies the founder tree itself at boot, so its leaf/fold must agree
   * with the STM's and Python's BYTE-FOR-BYTE. A divergence here is silent (images
   * just stop verifying), so it is asserted rather than assumed. The nRF reads the
   * image through a callback (flash_area on device, a flat buffer here), which is
   * exactly why the logic is shared instead of reimplemented. */
  {
    struct { const uint8_t *buf; uint32_t len; } shapes[] = {
        {NRF_IMAGE, NRF_IMAGE_LEN},  /* classic   */
        {PQ_IMAGE, PQ_IMAGE_LEN},    /* PQ-native */
    };
    const unsigned char (*proofs[])[32] = {NRF_PROOF, PQ_PROOF};
    const unsigned int counts[] = {NRF_PROOF_COUNT, PQ_PROOF_COUNT};
    const char *names[] = {"classic", "PQ-native"};

    for (int i = 0; i < 2; i++) {
      struct flat_image src = {shapes[i].buf, shapes[i].len};

      /* 1. same image hash as Python/STM -- this IS the leaf value now */
      uint8_t nrf_hash[32];
      uint8_t stm_hash[32];
      if (pq_image_hash(flat_read, &src, shapes[i].len, nrf_hash) != 0) {
        printf("FAIL: nRF pq_image_hash(%s) failed\n", names[i]);
        fails++;
        continue;
      }
      if (nrf_image_hash(shapes[i].buf, shapes[i].len, stm_hash) !=
          sectrue) {
        printf("FAIL: STM nrf_image_hash(%s) failed\n", names[i]);
        fails++;
        continue;
      }
      if (memcmp(nrf_hash, stm_hash, 32) != 0) {
        printf("FAIL: nRF image hash != STM image hash (%s)\n", names[i]);
        fails++;
        continue;
      }

      /* 2. same leaf: H(0x00 || image_hash), computed both ways */
      uint8_t nrf_leaf[32];
      merkle_proof_node_t stm_leaf;
      {
        SHA256_CTX c;
        const uint8_t p0 = 0x00;
        sha256_Init(&c);
        sha256_Update(&c, &p0, 1);
        sha256_Update(&c, nrf_hash, 32);
        sha256_Final(&c, nrf_leaf);
      }
      merkle_leaf_hash(stm_hash, 32, &stm_leaf);
      if (memcmp(nrf_leaf, stm_leaf.bytes, 32) != 0) {
        printf("FAIL: nRF leaf != STM leaf (%s)\n", names[i]);
        fails++;
        continue;
      }

      /* 3. same fold result: nRF folds to the signed modelRoot */
      uint8_t nrf_root[32];
      pq_merkle_fold(nrf_leaf, (const uint8_t *)proofs[i], counts[i], nrf_root);
      if (memcmp(nrf_root, NRF_MODEL_ROOT, 32) != 0) {
        printf("FAIL: nRF fold != modelRoot (%s)\n", names[i]);
        fails++;
        continue;
      }
      printf("nRF impl (%s): image hash + leaf + fold == STM/Python: OK\n",
             names[i]);
    }

    /* the nRF must reject a malformed image too, not hash whatever is there */
    struct flat_image junk = {(const uint8_t *)"not-an-mcuboot-image", 20};
    uint8_t junk_hash[32];
    if (pq_image_hash(flat_read, &junk, 20, junk_hash) == 0) {
      printf("FAIL: nRF pq_image_hash accepted a malformed image\n");
      fails++;
    } else {
      printf("nRF impl: malformed image rejected: OK\n");
    }

    /* ---- shape check: the ROGUE-TLV gap the fold cannot see ---------------- */
    bool present = false;
    struct flat_image good_pq = {PQ_IMAGE, PQ_IMAGE_LEN};
    if (pq_region_shape_ok(flat_read, &good_pq, PQ_IMAGE_LEN, &present) != 0 ||
        !present) {
      printf("FAIL: genuine founder region rejected by shape check\n");
      fails++;
    } else {
      printf("shape check: genuine founder region accepted (present): OK\n");
    }

    /* A classic image has no founder material -> nothing to check, present=false. */
    struct flat_image classic = {NRF_IMAGE, NRF_IMAGE_LEN};
    present = true;
    if (pq_region_shape_ok(flat_read, &classic, NRF_IMAGE_LEN, &present) != 0 ||
        present) {
      printf("FAIL: classic image mishandled by shape check\n");
      fails++;
    } else {
      printf("shape check: classic image -> no founder material: OK\n");
    }

    /* THE POINT: the rogue image still FOLDS (leaf untouched), so neither the
     * Merkle fold nor a founder signature re-verify would catch it -- but MCUboot
     * would reject it, and the shape check does too. */
    if (harness_ota_gate(PQ_OTA_ROGUE, PQ_OTA_ROGUE_LEN, &root, DEVICE_MODEL_ID, NULL,
                       NULL) != sectrue) {
      printf("FAIL: rogue-TLV premise broken (it should still fold)\n");
      fails++;
    } else {
      printf("rogue TLV: still folds to modelRoot (fold alone is blind): OK\n");
    }
    struct flat_image rogue = {PQ_IMAGE_ROGUE, PQ_IMAGE_ROGUE_LEN};
    if (pq_region_shape_ok(flat_read, &rogue, PQ_IMAGE_ROGUE_LEN, NULL) == 0) {
      printf("FAIL: shape check ACCEPTED a rogue TLV (brick path open)\n");
      fails++;
    } else {
      printf("shape check: rogue TLV in founder region rejected: OK\n");
    }
  }

  /* a truncated / non-MCUboot image must be rejected outright (signed-region
   * parse fails) rather than hashing whatever bytes are present */
  if (nrf_image_verify_in_tree((const uint8_t *)"not-an-mcuboot-image", 20,
                         (const merkle_proof_node_t *)NRF_PROOF, NRF_PROOF_COUNT,
                         &root) != secfalse) {
    printf("FAIL: malformed image accepted\n");
    fails++;
  } else {
    printf("malformed image rejected (bad magic / signed-region parse): OK\n");
  }

  /* another model's OTA: folds to modelRoot fine, rejected on model id */
  if (harness_ota_gate(OTHER_OTA, OTHER_OTA_LEN, &root, DEVICE_MODEL_ID, NULL,
                     NULL) != secfalse) {
    printf("FAIL: other model's OTA accepted (cross-model!)\n");
    fails++;
  } else {
    printf("other model's OTA rejected on model id (folds OK): OK\n");
  }

  /* NOT tested here: an oversized proof_count. That bound belongs to whoever
   * hands the primitives a co_path -- on device, nrf_staging.c checks
   * co_path_count against MODEL_TREE_MAX_PROOF_NODES before anything reads it,
   * and wf_nrf_ota.c checks it again on the wire path. boot_header_verify_slot
   * itself trusts the count, deliberately. Asserting it against the harness's own
   * unpacker above would only be testing the harness. */

  printf("\nRESULT: %s\n",
         fails == 0 ? "C matches Python, all rejects OK" : "FAILURES");
  return fails ? 1 : 0;
}
