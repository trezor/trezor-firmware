#!/usr/bin/env python3
"""Generate a lossless, prefix-compressed English BIP39 dictionary."""

import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "bip39_english_compact.h"


def generate() -> str:
    source = (ROOT / "bip39_english.c").read_text()
    words = re.findall(r'"([a-z]+)"', source)
    assert len(words) == 2048 and words == sorted(set(words))
    data = bytearray()
    previous = ""
    for word in words:
        prefix = 0
        while (
            prefix < min(len(previous), len(word)) and previous[prefix] == word[prefix]
        ):
            prefix += 1
        suffix = word[prefix:]
        assert len(word) <= 8 and 0 < len(suffix) <= 8
        data.append((prefix << 4) | len(suffix))
        packed = sum((ord(char) - ord("a")) << (5 * i) for i, char in enumerate(suffix))
        data.extend(packed.to_bytes((5 * len(suffix) + 7) // 8, "little"))
        previous = word
    rows = [
        "  " + ", ".join(f"0x{x:02x}" for x in data[i : i + 12]) + ","
        for i in range(0, len(data), 12)
    ]
    content = (
        "/* SPDX-License-Identifier: MIT */\n"
        "/* Generated by crypto/tools/gen_bip39_compact.py; do not edit. */\n"
        "#pragma once\n#include <stdint.h>\n"
        "/* Header: shared prefix length (high nibble), suffix length (low).\n"
        " * Suffix letters use five bits each, least significant bits first. */\n"
        f"static const uint8_t bip39_english_compact[{len(data)}] = {{\n"
        + "\n".join(rows)
        + "\n};\n"
    )
    return subprocess.check_output(["clang-format"], input=content, text=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit("Regenerate with crypto/tools/gen_bip39_compact.py")
    else:
        OUTPUT.write_text(result)


if __name__ == "__main__":
    main()
